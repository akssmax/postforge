#!/usr/bin/env node
// Compiles config/design YAML into src/lib/design-config/generated.ts
import fs from "fs";
import path from "path";
import { createRequire } from "module";
import { fileURLToPath } from "url";

const require = createRequire(import.meta.url);
const yaml = require("js-yaml");

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const CONFIG = path.join(ROOT, "config", "design");
const OUT = path.join(ROOT, "src", "lib", "design-config", "generated.ts");

function loadDir(subdir) {
  const dir = path.join(CONFIG, subdir);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".yaml") || f.endsWith(".yml"))
    .map((f) => yaml.load(fs.readFileSync(path.join(dir, f), "utf8")));
}

function loadFile(rel) {
  const file = path.join(CONFIG, rel);
  if (!fs.existsSync(file)) return null;
  return yaml.load(fs.readFileSync(file, "utf8"));
}

const campaigns = loadDir("campaign");
const patterns = loadDir("patterns");
const recipes = loadDir("recipes");
const layouts = loadDir("layouts");
const systems = loadDir("systems");
const overlays = loadDir("overlays");
const visuals = loadFile("visuals/strategy.yaml") ?? {
  featured: {},
  pattern: {},
  decoration: {},
  color: {},
};

const payload = {
  campaigns,
  patterns,
  recipes,
  layouts,
  systems,
  overlays,
  visuals,
};

const source = `/* AUTO-GENERATED by scripts/compile-design-config.mjs — do not edit by hand */
/* eslint-disable */
export const designConfigData = ${JSON.stringify(payload, null, 2)} as const;
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, source, "utf8");
console.log(
  `Wrote ${OUT} (${campaigns.length} campaigns, ${patterns.length} patterns, ${recipes.length} recipes, ${layouts.length} layouts, ${systems.length} systems, ${overlays.length} overlays)`,
);
